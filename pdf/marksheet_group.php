<?php
/**
 * Group marksheet PDF for an exam (all students), with optional status filter.
 * Branches: terminal = marks-only sheet; final = SGPA sheet.
 * Admin only.
 */
require_once __DIR__ . '/../includes/init.php';
require_once __DIR__ . '/../includes/result_engine.php';
require_once __DIR__ . '/../includes/academics.php';
$user = require_role(ROLE_SUPERADMIN);

$examId = (int) ($_GET['exam_id'] ?? 0);
$exam = $examId ? db_one('SELECT e.*, sm.name AS semester_name FROM exams e JOIN semesters sm ON sm.id = e.semester_id WHERE e.id = ?', [$examId]) : null;
if (!$exam) { header('Location: ' . url('admin/index.php')); exit; }

$isTerminal = exam_is_terminal($exam);
$filter = $_GET['filter'] ?? 'all';
$students = exam_students($examId);
$rows = [];
foreach ($students as $st) {
    if ($isTerminal) {
        $sum = terminal_student_summary($examId, (int) $st['id']);
        if (!$sum || !$sum['subjects']) continue;
        $status = $sum['overall'];
        if ($filter === 'all' || $status === $filter || ($filter === 'retained' && $status !== 'Pass')) {
            $rows[] = array_merge($st, ['status' => $status, 'sum' => $sum]);
        }
    } else {
        $r = db_one('SELECT * FROM results WHERE student_id = ? AND exam_id = ?', [$st['id'], $examId]);
        if (!$r) continue;
        if ($filter === 'all' || $r['result_status'] === $filter || ($filter === 'retained' && $r['result_status'] !== 'Pass')) {
            $rows[] = array_merge($st, ['r' => $r]);
        }
    }
}
usort($rows, fn($a, $b) => strcmp($a['student_code'], $b['student_code']));

require_once __DIR__ . '/../lib/fpdf/fpdf.php';

if (!function_exists('pdf_ascii')) {
function pdf_ascii($s)
{
    $s = trim((string) $s);
    $out = @iconv('UTF-8', 'ISO-8859-1//TRANSLIT', $s);
    return $out === false ? preg_replace('/[^\x20-\x7E]/', '', $s) : $out;
}
function sp0($n) { return number_format((float) $n, 0); }
function sp2($n) { return number_format((float) $n, 2); }
}

if (!class_exists('GroupPdf', false)) {
class GroupPdf extends FPDF
{
    public function Footer()
    {
        $this->SetY(-15);
        $this->SetFont('Helvetica', 'I', 7);
        $this->SetTextColor(140, 140, 140);
        $this->Cell(0, 10, 'Generated by Web-Based Result Management System (Academic Project). Page ' . $this->PageNo() . '/{nb}', 0, 0, 'C');
    }
}
}

$p = new GroupPdf('L', 'mm', 'A4');
$p->AliasNbPages();
$p->SetAutoPageBreak(true, 18);
$p->SetDrawColor(170, 180, 195);

$inst = get_setting('institute_name', 'Institute of Science & Technology');
$instAddr = get_setting('institute_address', '');

$cols = $isTerminal
    ? ['SN', 'ROLL', 'STUDENT NAME', 'CREDIT', 'FULL MARKS', 'OBTAINED', 'PERCENTAGE', 'STATUS', 'REMARKS']
    : ['SN', 'ROLL', 'STUDENT NAME', 'CREDIT', 'SGPA', 'CGPA', 'CR. PT.', 'TOTAL MARKS', 'STATUS', 'REMARKS'];
$colW = $isTerminal
    ? ['SN'=>10, 'ROLL'=>32, 'STUDENT NAME'=>86, 'CREDIT'=>18, 'FULL MARKS'=>26, 'OBTAINED'=>26, 'PERCENTAGE'=>26, 'STATUS'=>26, 'REMARKS'=>34]
    : ['SN'=>10, 'ROLL'=>30, 'STUDENT NAME'=>72, 'CREDIT'=>16, 'SGPA'=>21, 'CGPA'=>21, 'CR. PT.'=>22, 'TOTAL MARKS'=>27, 'STATUS'=>26, 'REMARKS'=>39];
$W = 284;

if (!function_exists('groupHeader')) {
function groupHeader($p, $W, $colW, $cols)
{
    $p->SetFillColor(230, 237, 246);
    $p->SetTextColor(25, 25, 35);
    $p->SetFont('Helvetica', 'B', 8.5);
    foreach ($cols as $k) $p->Cell($colW[$k], 8, $k, 1, 0, 'C', true);
    $p->Ln();
}
}

$pass = count(array_filter($rows, fn($x) => ($x['status'] ?? '') === 'Pass' || ($x['r']['result_status'] ?? '') === 'Pass'));
$retained = count(array_filter($rows, fn($x) => ($x['status'] ?? '') !== 'Pass' && ($x['r']['result_status'] ?? '') !== 'Pass'));

$p->AddPage();
$p->SetTextColor(20, 20, 30);
$p->SetFont('Helvetica', 'B', 16);
$p->Cell($W, 9, pdf_ascii($inst), 0, 1, 'C');
$p->SetFont('Helvetica', '', 10);
$p->SetTextColor(70, 70, 80);
$p->Cell($W, 5, pdf_ascii($instAddr), 0, 1, 'C');
$p->SetTextColor(20, 20, 30);
$p->Ln(1);

$p->SetFillColor(45, 85, 145);
$p->SetTextColor(255, 255, 255);
$p->SetFont('Helvetica', 'B', 13);
$p->Cell($W, 9, ($isTerminal ? 'CONSOLIDATED TERMINAL MARKS SHEET - ' : 'CONSOLIDATED SEMESTER RESULT - ') . pdf_ascii(strtoupper($exam['name'])), 1, 1, 'C', true);
$p->SetFont('Helvetica', '', 10.5);
$p->SetTextColor(30, 30, 40);
$p->SetFillColor(240, 244, 250);
$p->Cell($W, 7, pdf_ascii('Program: BCA   |   Semester: ' . $exam['semester_name'] . '   |   Total Students: ' . count($rows) .
    '   |   Pass: ' . $pass . '   |   Retained/Other: ' . $retained), 1, 1, 'C', true);
$p->Ln(3);

groupHeader($p, $W, $colW, $cols);

$p->SetFont('Helvetica', '', 8.5);
$sn = 0;
foreach ($rows as $row) {
    if ($p->GetY() > 175) { $p->AddPage(); groupHeader($p, $W, $colW, $cols); }
    $sn++;
    $st = $row;
    if ($isTerminal) {
        $status = $row['status'];
        $sum = $row['sum'];
        $credits = array_sum(array_map(static fn($d) => (float) $d['credit_hours'], $sum['subjects']));
        $passed = $status === 'Pass';
        $fill = !$passed;
        if ($fill) $p->SetFillColor(255, 240, 240);
        $p->Cell($colW['SN'], 6.4, $sn, 1, 0, 'C', $fill);
        $p->Cell($colW['ROLL'], 6.4, pdf_ascii($st['student_code']), 1, 0, 'C', $fill);
        $p->Cell($colW['STUDENT NAME'], 6.4, pdf_ascii($st['full_name']), 1, 0, 'L', $fill);
        $p->Cell($colW['CREDIT'], 6.4, sp0($credits), 1, 0, 'C', $fill);
        $p->Cell($colW['FULL MARKS'], 6.4, sp0($sum['full']), 1, 0, 'C', $fill);
        $p->Cell($colW['OBTAINED'], 6.4, sp0($sum['total']), 1, 0, 'C', $fill);
        $p->Cell($colW['PERCENTAGE'], 6.4, number_format($sum['percentage'], 1) . '%', 1, 0, 'C', $fill);
        $p->Cell($colW['STATUS'], 6.4, $status, 1, 0, 'C', $fill);
        $p->Cell($colW['REMARKS'], 6.4, $passed ? 'PROMOTED' : '', 1, 0, 'C', $fill);
        $p->Ln();
    } else {
        $r = $row['r'];
        $passed = $r['result_status'] === 'Pass';
        $fill = !$passed;
        if ($fill) $p->SetFillColor(255, 240, 240);
        $p->Cell($colW['SN'], 6.4, $sn, 1, 0, 'C', $fill);
        $p->Cell($colW['ROLL'], 6.4, pdf_ascii($st['student_code']), 1, 0, 'C', $fill);
        $p->Cell($colW['STUDENT NAME'], 6.4, pdf_ascii($st['full_name']), 1, 0, 'L', $fill);
        $p->Cell($colW['CREDIT'], 6.4, sp0($r['total_credits']), 1, 0, 'C', $fill);
        $p->Cell($colW['SGPA'], 6.4, sp2($r['sgpa']), 1, 0, 'C', $fill);
        $p->Cell($colW['CGPA'], 6.4, sp2($r['cgpa']), 1, 0, 'C', $fill);
        $p->Cell($colW['CR. PT.'], 6.4, sp0($r['total_credit_points']), 1, 0, 'C', $fill);
        $total = (float) db_val('SELECT COALESCE(SUM(total_marks),0) FROM result_details WHERE result_id=?', [$r['id']]);
        $full = (float) db_val('SELECT COALESCE(SUM(max_marks),0) FROM result_details WHERE result_id=?', [$r['id']]);
        $p->Cell($colW['TOTAL MARKS'], 6.4, sp0($total) . '/' . sp0($full), 1, 0, 'C', $fill);
        $p->Cell($colW['STATUS'], 6.4, $r['result_status'], 1, 0, 'C', $fill);
        $p->Cell($colW['REMARKS'], 6.4, $passed ? 'PROMOTED' : '', 1, 0, 'C', $fill);
        $p->Ln();
    }
}

$p->Ln(2);
$p->SetFont('Helvetica', 'B', 9);
$p->Cell($W, 6, pdf_ascii('Signature of Examiner: ______________________          Controller of Examinations: ______________________          Principal / HoD: ______________________'), 'T', 1, 'C');
$p->Ln(2);
$p->SetFont('Helvetica', 'I', 7.5);
$p->SetTextColor(120, 120, 120);
$note = $isTerminal
    ? 'Note: Terminal examinations are independent marks-only sheets. Document generated for academic/project purposes.'
    : 'Note: Computed under single-total grading model. GPA figures use 4.0 scale. Document generated for academic/project purposes.';
$p->Cell($W, 5, pdf_ascii($note), 0, 1, 'C');

$p->Output('GroupMarksheet_' . $exam['name'] . '.pdf', 'I');